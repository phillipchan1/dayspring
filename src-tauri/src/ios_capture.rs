//! Native capture on iOS: VisionKit's document camera for page scans, and
//! PhotosUI's picker for photos (NATIVE_FEEL_AUDIT §5).
//!
//! The web paths go through WebKit's file sheet: a menu, then the camera one
//! shot at a time with no deskew, or the photo library behind an extra tap.
//! These present the system's own controllers instead and hand the result
//! back as bytes, which src/lib/nativeCapture.ts turns into the same `File`s
//! the web paths produce — so `transcribePages` and the image popover's
//! `handleFiles` don't change.
//!
//! Neither VisionKit nor PhotosUI has bindings among the objc2 crates already
//! in the lockfile, so this is raw `msg_send!` against runtime classes, the
//! way ios_oauth.rs and the selection actions in lib.rs are written. The two
//! frameworks are `dlopen`ed on first use rather than linked: the Xcode
//! project in gen/apple is regenerated by `tauri ios init` in CI, so a link
//! added there would not survive, and a class lookup needs the framework
//! loaded, not linked.
//!
//! Like the other iOS commands, these compile everywhere so the front end can
//! call them without a cfg of its own; off iOS they answer "unsupported" and
//! the web path runs.
//!
//! Reply format (both commands), little-endian:
//!   u32 count, then per item: u32 mime length, mime bytes, u32 length, bytes.

/// Off iOS, and on devices without a document camera (the simulator).
pub const UNSUPPORTED: &str = "unsupported";

/// Scan one or more pages with VisionKit. Resolves to the pages as JPEG, an
/// empty reply when the writer cancels, or an error (`"unsupported"` when
/// the web `<input capture>` path should be used instead).
///
/// `async` + `spawn_blocking` for the same reason as `start_oauth_session`:
/// presentation and the delegate both need the main run loop, so the wait
/// must not sit on it.
#[tauri::command]
pub async fn scan_document_pages() -> Result<tauri::ipc::Response, String> {
  #[cfg(not(target_os = "ios"))]
  {
    return Err(UNSUPPORTED.into());
  }
  #[cfg(target_os = "ios")]
  {
    let pages = tauri::async_runtime::spawn_blocking(imp::scan_blocking)
      .await
      .map_err(|e| format!("scan waiter failed: {e}"))??;
    Ok(tauri::ipc::Response::new(imp::encode(&pages)))
  }
}

/// Pick photos with PHPickerViewController: images only, multi-select, in the
/// order tapped. `limit` 0 is unlimited. Same reply shape as the scan.
#[tauri::command]
pub async fn pick_photos(limit: u32) -> Result<tauri::ipc::Response, String> {
  #[cfg(not(target_os = "ios"))]
  {
    let _ = limit;
    return Err(UNSUPPORTED.into());
  }
  #[cfg(target_os = "ios")]
  {
    let photos = tauri::async_runtime::spawn_blocking(move || imp::pick_blocking(limit as usize))
      .await
      .map_err(|e| format!("photo picker waiter failed: {e}"))??;
    Ok(tauri::ipc::Response::new(imp::encode(&photos)))
  }
}

#[cfg(target_os = "ios")]
mod imp {
  use super::UNSUPPORTED;
  use block2::RcBlock;
  use objc2::rc::{autoreleasepool, Allocated, Retained};
  use objc2::runtime::{AnyClass, AnyObject, AnyProtocol, ClassBuilder, NSObject, Sel};
  use objc2::{msg_send, sel, ClassType};
  use objc2_foundation::NSString;
  use std::ffi::{c_char, c_int, c_void, CStr};
  use std::sync::atomic::{AtomicUsize, Ordering};
  use std::sync::mpsc::{channel, Sender};
  use std::sync::{Arc, Mutex, OnceLock};
  use std::time::Duration;

  /// `(mime type, bytes)` per page or photo, in order.
  pub type Captured = Vec<(String, Vec<u8>)>;
  pub type Reply = Result<Captured, String>;
  pub type Waiter = Mutex<Option<Sender<Reply>>>;

  static SCAN_WAITER: Waiter = Mutex::new(None);
  static PICK_WAITER: Waiter = Mutex::new(None);

  /// The delegates, created once and kept for the life of the process — both
  /// controllers hold their delegate weakly.
  static SCAN_DELEGATE: OnceLock<usize> = OnceLock::new();
  static PICK_DELEGATE: OnceLock<usize> = OnceLock::new();

  /// Long enough for a slow, careful scan of a long entry. A controller that
  /// never answers (it shouldn't) frees the slot after this.
  const WAIT: Duration = Duration::from_secs(30 * 60);

  /// High enough for handwriting to survive transcription, low enough that
  /// eight pages cross the bridge in a blink.
  const JPEG_QUALITY: f64 = 0.82;

  /// What a picked photo can be read as, in the order worth asking. The
  /// image popover takes JPEG, PNG, GIF and WebP (attachmentInsert.ts).
  const IMAGE_TYPES: &[(&str, &str)] = &[
    ("public.jpeg", "image/jpeg"),
    ("public.png", "image/png"),
    ("com.compuserve.gif", "image/gif"),
    ("org.webmproject.webp", "image/webp"),
  ];

  /// PHPickerConfigurationAssetRepresentationModeCompatible: HEIC arrives as
  /// JPEG, which the web layer can show and upload.
  const REPRESENTATION_COMPATIBLE: isize = 2;
  /// PHPickerConfigurationSelectionOrdered (iOS 15): numbered badges, and the
  /// results come back in the order tapped.
  const SELECTION_ORDERED: isize = 1;

  extern "C" {
    fn dlopen(path: *const c_char, mode: c_int) -> *mut c_void;
  }
  const RTLD_LAZY: c_int = 0x1;

  #[link(name = "UIKit", kind = "framework")]
  extern "C" {
    // CGFloat is f64 on every 64-bit Apple platform. Returns an autoreleased
    // NSData, or nil.
    fn UIImageJPEGRepresentation(image: *mut AnyObject, compression_quality: f64) -> *mut AnyObject;
  }

  pub fn encode(items: &Captured) -> Vec<u8> {
    let total = 4 + items.iter().map(|(mime, data)| 8 + mime.len() + data.len()).sum::<usize>();
    let mut out = Vec::with_capacity(total);
    out.extend_from_slice(&(items.len() as u32).to_le_bytes());
    for (mime, data) in items {
      out.extend_from_slice(&(mime.len() as u32).to_le_bytes());
      out.extend_from_slice(mime.as_bytes());
      out.extend_from_slice(&(data.len() as u32).to_le_bytes());
      out.extend_from_slice(data);
    }
    out
  }

  pub fn scan_blocking() -> Reply {
    run(&SCAN_WAITER, present_scanner)
  }

  pub fn pick_blocking(limit: usize) -> Reply {
    run(&PICK_WAITER, move || present_picker(limit))
  }

  fn take(waiter: &Waiter) -> Option<Sender<Reply>> {
    waiter.lock().ok().and_then(|mut slot| slot.take())
  }

  fn finish(waiter: &Waiter, reply: Reply) {
    if let Some(tx) = take(waiter) {
      let _ = tx.send(reply);
    }
  }

  /// Present on the main thread, then wait (off it) for the delegate.
  fn run<F>(waiter: &'static Waiter, open: F) -> Reply
  where
    F: FnOnce() -> Result<(), String> + Send + 'static,
  {
    let (tx, rx) = channel();
    match waiter.lock() {
      Ok(mut slot) => {
        // The front end never asks twice at once (nativeCapture.ts shares the
        // promise in flight), so a request still waiting here is one whose
        // sheet is already gone. Let it go rather than refuse forever.
        if let Some(stale) = slot.replace(tx) {
          let _ = stale.send(Err("superseded".into()));
        }
      }
      Err(_) => return Err("capture state unavailable".into()),
    }
    crate::run_on_main(move || {
      if let Err(err) = open() {
        finish(waiter, Err(err));
      }
    });
    match rx.recv_timeout(WAIT) {
      Ok(reply) => reply,
      Err(_) => {
        let _ = take(waiter);
        Err("timed out".into())
      }
    }
  }

  fn load_framework(path: &CStr) {
    // SAFETY: a constant, NUL-terminated path to a public system framework.
    // The handle is never closed; the framework stays loaded for the process.
    let _ = unsafe { dlopen(path.as_ptr(), RTLD_LAZY) };
  }

  /// One shared delegate object per class, created on first use.
  fn delegate_object(
    slot: &'static OnceLock<usize>,
    class: fn() -> Option<&'static AnyClass>,
  ) -> Result<*mut AnyObject, String> {
    let addr = *slot.get_or_init(|| {
      let Some(cls) = class() else { return 0 };
      // SAFETY: alloc/init of our own NSObject subclass; init-family returns
      // Option. `into_raw` keeps the +1 for the life of the process.
      unsafe {
        let allocated: Allocated<NSObject> = msg_send![cls, alloc];
        let obj: Option<Retained<NSObject>> = msg_send![allocated, init];
        obj.map(|o| Retained::into_raw(o) as usize).unwrap_or(0)
      }
    });
    if addr == 0 {
      Err(UNSUPPORTED.into())
    } else {
      Ok(addr as *mut AnyObject)
    }
  }

  fn present(vc: &AnyObject) -> Result<(), String> {
    let host = crate::top_view_controller();
    if host.is_null() {
      return Err("no window to present from".into());
    }
    // SAFETY: main thread (called from `run`'s main-thread closure); `host`
    // is a live view controller and `vc` a freshly created one.
    unsafe {
      let _: () = msg_send![
        host,
        presentViewController: vc,
        animated: true,
        completion: std::ptr::null::<AnyObject>()
      ];
    }
    Ok(())
  }

  fn dismiss(vc: *mut AnyObject) {
    if vc.is_null() {
      return;
    }
    // SAFETY: delegate callbacks arrive on the main thread with the
    // presenting controller, which is still alive.
    unsafe {
      let _: () = msg_send![
        vc,
        dismissViewControllerAnimated: true,
        completion: std::ptr::null::<AnyObject>()
      ];
    }
  }

  /// Copy an NSData's bytes out. Nil or empty gives None.
  fn nsdata_bytes(data: *mut AnyObject) -> Option<Vec<u8>> {
    if data.is_null() {
      return None;
    }
    // SAFETY: `data` is an NSData; `bytes` is valid for `length` bytes while
    // the object lives, and it is copied before returning.
    unsafe {
      let len: usize = msg_send![data, length];
      if len == 0 {
        return None;
      }
      let ptr: *const c_void = msg_send![data, bytes];
      if ptr.is_null() {
        return None;
      }
      Some(std::slice::from_raw_parts(ptr as *const u8, len).to_vec())
    }
  }

  fn jpeg_of(image: *mut AnyObject) -> Option<Vec<u8>> {
    if image.is_null() {
      return None;
    }
    // SAFETY: `image` is a UIImage; the NSData that comes back is
    // autoreleased and read before the caller's pool drains.
    nsdata_bytes(unsafe { UIImageJPEGRepresentation(image, JPEG_QUALITY) })
  }

  fn describe(error: *mut AnyObject) -> String {
    if error.is_null() {
      return "the camera stopped".into();
    }
    // SAFETY: `error` is an NSError; UTF8String is valid while `desc` lives.
    unsafe {
      let desc: *mut AnyObject = msg_send![error, localizedDescription];
      if desc.is_null() {
        return "the camera stopped".into();
      }
      let utf8: *const c_char = msg_send![desc, UTF8String];
      if utf8.is_null() {
        return "the camera stopped".into();
      }
      CStr::from_ptr(utf8).to_string_lossy().into_owned()
    }
  }

  fn responds(obj: &AnyObject, selector: Sel) -> bool {
    // SAFETY: -respondsToSelector: is on every NSObject.
    unsafe { msg_send![obj, respondsToSelector: selector] }
  }

  // ── Page scan ─────────────────────────────────────────────────────────────

  fn present_scanner() -> Result<(), String> {
    load_framework(c"/System/Library/Frameworks/VisionKit.framework/VisionKit");
    let cls = AnyClass::get(c"VNDocumentCameraViewController").ok_or(UNSUPPORTED)?;
    // SAFETY: +isSupported is a BOOL class property (iOS 13+). It is false
    // on the simulator and on devices without the hardware.
    let supported: bool = unsafe { msg_send![cls, isSupported] };
    if !supported {
      return Err(UNSUPPORTED.into());
    }
    let delegate = delegate_object(&SCAN_DELEGATE, scan_delegate_class)?;
    // SAFETY: alloc/init of a UIViewController subclass on the main thread.
    let vc: Option<Retained<AnyObject>> = unsafe {
      let allocated: Allocated<AnyObject> = msg_send![cls, alloc];
      msg_send![allocated, init]
    };
    let vc = vc.ok_or("could not open the camera")?;
    // SAFETY: the delegate implements the three methods VisionKit calls.
    unsafe {
      let _: () = msg_send![&*vc, setDelegate: delegate];
    }
    present(&vc)
  }

  fn scan_delegate_class() -> Option<&'static AnyClass> {
    if let Some(cls) = AnyClass::get(c"DayspringDocumentCameraDelegate") {
      return Some(cls);
    }
    let mut builder = ClassBuilder::new(c"DayspringDocumentCameraDelegate", NSObject::class())?;
    // SAFETY: each signature matches VNDocumentCameraViewControllerDelegate:
    // `- (void)…:(VNDocumentCameraViewController *)c didFinishWithScan:(VNDocumentCameraScan *)s`,
    // `- (void)…DidCancel:(VNDocumentCameraViewController *)c`,
    // `- (void)…:(VNDocumentCameraViewController *)c didFailWithError:(NSError *)e`.
    unsafe {
      builder.add_method(
        sel!(documentCameraViewController:didFinishWithScan:),
        scan_finished as unsafe extern "C-unwind" fn(_, _, _, _),
      );
      builder.add_method(
        sel!(documentCameraViewControllerDidCancel:),
        scan_cancelled as unsafe extern "C-unwind" fn(_, _, _),
      );
      builder.add_method(
        sel!(documentCameraViewController:didFailWithError:),
        scan_failed as unsafe extern "C-unwind" fn(_, _, _, _),
      );
    }
    if let Some(proto) = AnyProtocol::get(c"VNDocumentCameraViewControllerDelegate") {
      builder.add_protocol(proto);
    }
    Some(builder.register())
  }

  unsafe extern "C-unwind" fn scan_finished(
    _this: &NSObject,
    _cmd: Sel,
    controller: *mut AnyObject,
    scan: *mut AnyObject,
  ) {
    dismiss(controller);
    let Some(tx) = take(&SCAN_WAITER) else { return };
    if scan.is_null() {
      let _ = tx.send(Ok(Vec::new()));
      return;
    }
    let count: usize = msg_send![scan, pageCount];
    let Some(scan) = Retained::retain(scan) else {
      let _ = tx.send(Ok(Vec::new()));
      return;
    };
    // Encoding a dozen full-page JPEGs on the main thread would freeze the
    // sheet's dismissal; Apple's own sample reads `imageOfPageAtIndex:` on a
    // background queue. A Retained isn't Send, so the +1 crosses as an
    // address and is taken back on the far side.
    let addr = Retained::into_raw(scan) as usize;
    std::thread::spawn(move || encode_scan(addr, count, tx));
  }

  fn encode_scan(addr: usize, count: usize, tx: Sender<Reply>) {
    let scan = addr as *mut AnyObject;
    let mut pages: Captured = Vec::with_capacity(count);
    for index in 0..count {
      // One pool per page: each decoded image is tens of megabytes.
      let page = autoreleasepool(|_| {
        // SAFETY: `scan` is the VNDocumentCameraScan retained in
        // `scan_finished`; `index` is below its pageCount.
        let image: *mut AnyObject = unsafe { msg_send![scan, imageOfPageAtIndex: index] };
        jpeg_of(image)
      });
      if let Some(bytes) = page {
        pages.push(("image/jpeg".to_string(), bytes));
      }
    }
    // SAFETY: balances the retain in `scan_finished`.
    drop(unsafe { Retained::from_raw(scan) });
    let _ = tx.send(Ok(pages));
  }

  unsafe extern "C-unwind" fn scan_cancelled(_this: &NSObject, _cmd: Sel, controller: *mut AnyObject) {
    dismiss(controller);
    finish(&SCAN_WAITER, Ok(Vec::new()));
  }

  unsafe extern "C-unwind" fn scan_failed(
    _this: &NSObject,
    _cmd: Sel,
    controller: *mut AnyObject,
    error: *mut AnyObject,
  ) {
    dismiss(controller);
    finish(&SCAN_WAITER, Err(describe(error)));
  }

  // ── Photo picker ──────────────────────────────────────────────────────────

  fn present_picker(limit: usize) -> Result<(), String> {
    load_framework(c"/System/Library/Frameworks/PhotosUI.framework/PhotosUI");
    let config_cls = AnyClass::get(c"PHPickerConfiguration").ok_or(UNSUPPORTED)?;
    let picker_cls = AnyClass::get(c"PHPickerViewController").ok_or(UNSUPPORTED)?;
    let delegate = delegate_object(&PICK_DELEGATE, picker_delegate_class)?;

    // SAFETY: PHPickerConfiguration is an NSObject subclass with -init.
    let config: Option<Retained<AnyObject>> = unsafe {
      let allocated: Allocated<AnyObject> = msg_send![config_cls, alloc];
      msg_send![allocated, init]
    };
    let config = config.ok_or("could not open your photos")?;
    // SAFETY: NSInteger properties of PHPickerConfiguration (iOS 14+); the
    // two newer ones are checked for first.
    unsafe {
      let selection_limit = limit as isize;
      let _: () = msg_send![&*config, setSelectionLimit: selection_limit];
      if let Some(filter_cls) = AnyClass::get(c"PHPickerFilter") {
        let images: *mut AnyObject = msg_send![filter_cls, imagesFilter];
        if !images.is_null() {
          let _: () = msg_send![&*config, setFilter: images];
        }
      }
      if responds(&config, sel!(setPreferredAssetRepresentationMode:)) {
        let _: () = msg_send![&*config, setPreferredAssetRepresentationMode: REPRESENTATION_COMPATIBLE];
      }
      if responds(&config, sel!(setSelection:)) {
        let _: () = msg_send![&*config, setSelection: SELECTION_ORDERED];
      }
    }

    // SAFETY: -initWithConfiguration: is PHPickerViewController's initializer.
    let picker: Option<Retained<AnyObject>> = unsafe {
      let allocated: Allocated<AnyObject> = msg_send![picker_cls, alloc];
      msg_send![allocated, initWithConfiguration: &*config]
    };
    let picker = picker.ok_or("could not open your photos")?;
    // SAFETY: the delegate implements -picker:didFinishPicking:.
    unsafe {
      let _: () = msg_send![&*picker, setDelegate: delegate];
    }
    present(&picker)
  }

  fn picker_delegate_class() -> Option<&'static AnyClass> {
    if let Some(cls) = AnyClass::get(c"DayspringPhotoPickerDelegate") {
      return Some(cls);
    }
    let mut builder = ClassBuilder::new(c"DayspringPhotoPickerDelegate", NSObject::class())?;
    // SAFETY: matches PHPickerViewControllerDelegate's one required method,
    // `- (void)picker:(PHPickerViewController *)p didFinishPicking:(NSArray<PHPickerResult *> *)r`.
    unsafe {
      builder.add_method(
        sel!(picker:didFinishPicking:),
        picker_finished as unsafe extern "C-unwind" fn(_, _, _, _),
      );
    }
    if let Some(proto) = AnyProtocol::get(c"PHPickerViewControllerDelegate") {
      builder.add_protocol(proto);
    }
    Some(builder.register())
  }

  /// The photos of one pick, filled in as their data arrives (on background
  /// queues, in any order). The last one in sends the set, in picked order.
  struct Picking {
    slots: Mutex<Vec<Option<(String, Vec<u8>)>>>,
    remaining: AtomicUsize,
  }

  impl Picking {
    fn settle(&self, index: usize, item: Option<(String, Vec<u8>)>) {
      if let Ok(mut slots) = self.slots.lock() {
        if let Some(slot) = slots.get_mut(index) {
          *slot = item;
        }
      }
      if self.remaining.fetch_sub(1, Ordering::SeqCst) == 1 {
        let items: Captured = match self.slots.lock() {
          Ok(mut slots) => slots.drain(..).flatten().collect(),
          Err(_) => Vec::new(),
        };
        finish(&PICK_WAITER, Ok(items));
      }
    }
  }

  unsafe extern "C-unwind" fn picker_finished(
    _this: &NSObject,
    _cmd: Sel,
    picker: *mut AnyObject,
    results: *mut AnyObject,
  ) {
    dismiss(picker);
    let count: usize = if results.is_null() { 0 } else { msg_send![results, count] };
    if count == 0 {
      // Cancel, or swiped away: the picker reports an empty selection.
      finish(&PICK_WAITER, Ok(Vec::new()));
      return;
    }
    let picking = Arc::new(Picking {
      slots: Mutex::new(vec![None; count]),
      remaining: AtomicUsize::new(count),
    });
    for index in 0..count {
      let result: *mut AnyObject = msg_send![results, objectAtIndex: index];
      let provider: *mut AnyObject = if result.is_null() {
        std::ptr::null_mut()
      } else {
        msg_send![result, itemProvider]
      };
      if !load_photo(provider, index, &picking) {
        picking.settle(index, None);
      }
    }
  }

  /// Ask `provider` for the photo's bytes. False when there is nothing it
  /// can give (the slot is settled empty by the caller).
  fn load_photo(provider: *mut AnyObject, index: usize, picking: &Arc<Picking>) -> bool {
    if provider.is_null() {
      return false;
    }
    for &(type_id, mime) in IMAGE_TYPES {
      let ns_type = NSString::from_str(type_id);
      // SAFETY: NSItemProvider; the type identifier is an NSString.
      let has: bool = unsafe { msg_send![provider, hasItemConformingToTypeIdentifier: &*ns_type] };
      if !has {
        continue;
      }
      let picking = Arc::clone(picking);
      let block = RcBlock::new(move |data: *mut AnyObject, _error: *mut AnyObject| {
        picking.settle(index, nsdata_bytes(data).map(|bytes| (mime.to_string(), bytes)));
      });
      // SAFETY: `-loadDataRepresentationForTypeIdentifier:completionHandler:`
      // copies the block and calls it once, on a background queue, with an
      // NSData (or nil) and an NSError (or nil). It returns an NSProgress.
      unsafe {
        let _progress: *mut AnyObject = msg_send![
          provider,
          loadDataRepresentationForTypeIdentifier: &*ns_type,
          completionHandler: &*block
        ];
      }
      return true;
    }

    // Nothing the web layer reads as is: decode to a UIImage, send JPEG.
    let Some(image_cls) = AnyClass::get(c"UIImage") else { return false };
    // SAFETY: NSItemProvider; UIImage conforms to NSItemProviderReading.
    let can: bool = unsafe { msg_send![provider, canLoadObjectOfClass: image_cls] };
    if !can {
      return false;
    }
    let picking = Arc::clone(picking);
    let block = RcBlock::new(move |image: *mut AnyObject, _error: *mut AnyObject| {
      let bytes = autoreleasepool(|_| jpeg_of(image));
      picking.settle(index, bytes.map(|bytes| ("image/jpeg".to_string(), bytes)));
    });
    // SAFETY: as above; the block gets a UIImage (or nil) and an NSError.
    unsafe {
      let _progress: *mut AnyObject = msg_send![
        provider,
        loadObjectOfClass: image_cls,
        completionHandler: &*block
      ];
    }
    true
  }
}
